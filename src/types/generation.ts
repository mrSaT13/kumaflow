/**
 * Общие типы для «кто на самом деле собрал выдачу».
 *
 * Мозг подключён к двум поверхностям (AutoDJ и кнопка «Моя волна»), остальные
 * страницы считают локально. Без явного признака источника обе выдачи
 * выглядят одинаково, и проверить, работал ли мозг, было невозможно.
 */

/** Кто сформировал выдачу. */
export type GenerationSource =
  /** Мозга хватило на всю пачку, локальный ML не трогался */
  | 'brain'
  /** Мозг дал часть, локальный ML докладывал хвост */
  | 'mixed'
  /** Мозг не дал ничего: выключен, недоступен или ответил пустым */
  | 'local'

/** Почему мозг не отдал треки. Диагностика, а не влияние на выдачу. */
export type BrainSkipReason =
  /** Интеграция не настроена (нет enabled или baseUrl) */
  | 'off'
  /** В brainMode выбрано 'local' — мозг намеренно не спрашивается */
  | 'mode-local'
  /** Очередь ещё не на дозаправке (waveNeedsRefill == false) */
  | 'not-refill'
  /** Мозг ответил, но вернул 0 треков */
  | 'no-tracks'
  /** Ответили, но ни один external_id не нашёлся в локальном пуле */
  | 'unmatched'
  /** Сетевая/серверная ошибка */
  | 'error'

/** Человекочитаемая расшифровка — для UI и логов. */
export const BRAIN_SKIP_LABELS: Record<BrainSkipReason, string> = {
  off: 'интеграция не настроена',
  'mode-local': 'режим «локальный»',
  'not-refill': 'очередь ещё не на дозаправке',
  'no-tracks': 'мозг вернул 0 треков',
  unmatched: 'external_id не найдены в локальной фонотеке',
  error: 'ошибка обращения к мозгу',
}